#ifndef LLVM_LIB_TARGET_Z80_MCTARGETDESC_Z80INSTPRINTER_H
#define LLVM_LIB_TARGET_Z80_MCTARGETDESC_Z80INSTPRINTER_H

#include "llvm/MC/MCInstPrinter.h"

namespace llvm {
class Z80InstPrinter : public MCInstPrinter {
public:
  Z80InstPrinter(const MCAsmInfo &MAI, const MCInstrInfo &MII,
                 const MCRegisterInfo &MRI)
      : MCInstPrinter(MAI, MII, MRI) {}

  void printRegName(raw_ostream &O, MCRegister Reg) override;
  void printInst(const MCInst *MI, uint64_t Address, StringRef Annot,
                 const MCSubtargetInfo &STI, raw_ostream &O) override;

  // Autogenerated by TableGen.
  std::pair<const char *, uint64_t>
  getMnemonic(const MCInst &MI) const override;
  void printInstruction(const MCInst *MI, uint64_t Address, raw_ostream &O);
  static const char *getRegisterName(MCRegister Reg);

  static const char *getCondCodeName(unsigned CC);

private:
  void printOperand(const MCInst *MI, unsigned OpNo, raw_ostream &O);
  void printOperand(const MCInst *MI, uint64_t Address, unsigned OpNo,
                    raw_ostream &O) {
    printOperand(MI, OpNo, O);
  }
  void printCondCode(const MCInst *MI, unsigned OpNo, raw_ostream &O);
  void printDisp(const MCInst *MI, unsigned OpNo, raw_ostream &O);
};
} // namespace llvm

#endif
